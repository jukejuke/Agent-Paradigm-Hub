"""
编程提示词质量评审维度清单
========================

反思节点（Reflector）将依据这些维度对提示词进行逐条批评，
确保优化后的提示词能被 Trae / Claude Code / OpenCode 等编程智能体直接执行。
"""

# 每条为 (维度名, 评审要点说明)
PROMPT_EVALUATION_CRITERIA: list[tuple[str, str]] = [
    ("目标明确性", "任务目标是否清晰、无歧义，是否说明了要做什么、达到什么效果。"),
    ("上下文完整", "是否交代了技术栈、编程语言、项目背景、文件/目录路径、输入数据等必要上下文。"),
    ("步骤可执行", "是否给出编程智能体可以直接动手的执行步骤、范围或方法，避免空泛口号式描述。"),
    ("约束与禁忌", "是否明确不要做什么、不能修改哪些文件、禁止引入额外依赖等边界条件。"),
    ("验收标准", "是否有可验证的完成标准（如测试通过、无报错、功能清单齐全）。"),
    ("输出格式", "是否规定了输出形式（代码文件、说明文档、命令等）与具体格式。"),
    ("规模控制", "任务范围是否过大、是否需要拆分或限定改动范围，避免一次做太多。"),
]


def render_criteria() -> str:
    """
    将评审维度渲染为带编号的文本，供反思系统提示词引用

    Returns:
        形如 "1. 目标明确性：任务目标是否清晰、无歧义……" 的多行文本
    """
    lines = []
    for index, (name, desc) in enumerate(PROMPT_EVALUATION_CRITERIA, start=1):
        lines.append(f"{index}. {name}：{desc}")
    return "\n".join(lines)
